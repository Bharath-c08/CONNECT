import mongoose from 'mongoose';

const AiLogSchema = new mongoose.Schema(
  {
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
    },
    type: {
      type: String,
      enum: ['chat', 'standup', 'burnout_check'],
      default: 'chat',
    },
    prompt: {
      type: String,
      required: true,
    },
    response: {
      type: String,
      required: true,
    },
  },
  { timestamps: true }
);

export default mongoose.model('AiLog', AiLogSchema);
